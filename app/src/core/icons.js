/* 返回一个内联 SVG 字符串。size 默认 1em(随上下文字号缩放);可传 cls 追加类、stroke 改描边粗细。 */
export function icon(name, opts = {}) {
  const body = PATHS[name];
  if (!body) { console.warn('[icons] 未知图标:', name); return ''; }
  const size = opts.size != null ? opts.size : '1em';
  const cls = opts.cls ? ` ${opts.cls}` : '';
  const sw = opts.stroke || 2;
  return `<svg class="icn${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

/* 填充静态页面里的 <span data-icon="name">(可带 data-size)。
   主题键特殊处理:渲染 月+日 两枚图标,由 CSS 按 [data-theme] 切换显隐(见 tokens.css)。 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.iconDone) return;
    const name = el.getAttribute('data-icon');
    const size = el.getAttribute('data-size');
    const opts = size ? { size: Number(size) } : {};
    if (name === 'theme') {
      el.innerHTML = `<span class="icn-moon">${icon('moon', opts)}</span><span class="icn-sun">${icon('sun', opts)}</span>`;
    } else {
      el.innerHTML = icon(name, opts);
    }
    el.dataset.iconDone = '1';
  });
}
